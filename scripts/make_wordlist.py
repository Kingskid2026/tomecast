"""Rebuild ``src/tomecast/data/common_words.txt``, the name finder's list of ordinary words.

The list is generated from public-domain books (Project Gutenberg texts of works whose
copyright has expired), so it carries no license of its own. A word goes in when it appears
in *lowercase* at least ``MIN_COUNT`` times across the books, which is what separates ordinary
words from names: "holmes" never shows up in lowercase, "table" does.

Run it from the repo root (it downloads the books once into a cache folder)::

    uv run python scripts/make_wordlist.py [CACHE_DIR]
"""

from __future__ import annotations

import re
import sys
import urllib.request
from collections import Counter
from pathlib import Path

# Project Gutenberg book numbers: novels, history, science, philosophy and war, for variety.
BOOKS = {
    11: "Alice's Adventures in Wonderland",
    35: "The Time Machine",
    36: "The War of the Worlds",
    76: "Adventures of Huckleberry Finn",
    84: "Frankenstein",
    98: "A Tale of Two Cities",
    120: "Treasure Island",
    132: "The Art of War",
    345: "Dracula",
    1228: "On the Origin of Species",
    1260: "Jane Eyre",
    1342: "Pride and Prejudice",
    1400: "Great Expectations",
    1404: "The Federalist Papers",
    1661: "The Adventures of Sherlock Holmes",
    2701: "Moby Dick",
    3300: "The Wealth of Nations",
    1232: "The Prince",
    20203: "Autobiography of Benjamin Franklin",
    2554: "Crime and Punishment",
    1184: "The Count of Monte Cristo",
    1727: "The Odyssey",
    105: "Persuasion",
}
MIN_COUNT = 3
WORD = re.compile(r"[a-z]+(?:'[a-z]+)?")
OUTPUT = Path(__file__).resolve().parent.parent / "src" / "tomecast" / "data" / "common_words.txt"


def fetch(number: int, cache: Path) -> str:
    path = cache / f"pg{number}.txt"
    if not path.exists():
        url = f"https://www.gutenberg.org/cache/epub/{number}/pg{number}.txt"
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    text = path.read_text(encoding="utf-8", errors="replace")
    start = re.search(r"\*\*\* ?START OF [^\n]*\*\*\*", text)
    end = re.search(r"\*\*\* ?END OF [^\n]*\*\*\*", text)
    return text[start.end() if start else 0 : end.start() if end else len(text)]


def main() -> None:
    cache = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/tomecast-wordlist-cache")
    cache.mkdir(parents=True, exist_ok=True)
    counts: Counter[str] = Counter()
    for number in BOOKS:
        text = fetch(number, cache).replace("\u2019", "'")
        # Only words written entirely in lowercase count: split on anything else first.
        for token in re.findall(r"[A-Za-z]+(?:'[A-Za-z]+)?", text):
            if token.islower():
                counts[token] += 1
    words = sorted(w for w, n in counts.items() if n >= MIN_COUNT and "'" not in w and len(w) > 1)
    words += ["a", "i"]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Ordinary English words, for `tomecast names`. One per line, lowercase.\n"
        "# Generated by scripts/make_wordlist.py from public-domain Project Gutenberg texts\n"
        f"# ({len(BOOKS)} books): every word that appears in lowercase at least "
        f"{MIN_COUNT} times.\n"
        "# Public domain: it carries no license of its own.\n"
    )
    OUTPUT.write_text(header + "\n".join(sorted(set(words))) + "\n", encoding="utf-8")
    print(f"wrote {len(set(words)):,} words to {OUTPUT}")


if __name__ == "__main__":
    main()
