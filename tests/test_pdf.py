def known_pages() -> list[PdfPage]:
    """Five pages: an "Also by" page, contents, then a chapter over three pages with a running
    header, page numbers, a word hyphenated inside a page and one across a page break, a
    sentence across a page break, a footnote, a figure caption, a two-column page drawn in
    the wrong order, and a web address."""
    also_by = PageBuilder()
    also_by.heading("Also by O. Henry", size=16)
    for title in ("Cabbages and Kings", "The Four Million", "Heart of the West"):
        also_by.line(title)

    contents = PageBuilder()
    contents.heading("Contents", size=16)
    contents.line("Chapter One ........ 3")
    contents.line("Chapter Two ........ 9")
    contents.line("Chapter Three ........ 15")

    first = PageBuilder().header("THE GIFT OF THE MAGI")
    first.heading("Chapter One")
    first.paragraph(
        [
            "One dollar and eighty-seven cents. That was all. And sixty",
            "cents of it was in pennies. Pennies saved one and two at a",
            "time by bulldozing the grocer and the vegetable man and the butch-",
            "er until one’s cheeks burned with the silent imputation of",
            "parsimony that such close dealing implied. Three times Della^1^",
            "counted it. One dollar and eighty-seven cents. And the next",
            "day would be Christmas.",
        ]
    )
    first.paragraph(
        [
            "There was clearly nothing to do but flop down on the shabby",
            "little couch and howl. So Della did it. Which instigates the",
            "moral reflection that life is made up of sobs, sniffles, and",
            "smiles, with sniffles predominating. While the mistress of the",
            "home is gradually subsiding from the first stage to the sec-",
        ]
    )
    first.footnotes(["^1^ Della is the wife of James Dillingham Young."])
    first.footer("3")

    second = PageBuilder().header("THE GIFT OF THE MAGI")
    second.paragraph(
        [
            "ond, take a look at the home. A furnished flat at $8 per week.",
            "It did not exactly beggar description, but it certainly had",
            "that word on the lookout for the mendicancy squad.",
        ],
        indent=0,
    )
    second.picture(MARGIN + 60, 380, 200, 110)
    second.line("Figure 1: The flat at $8 per week.", size=9, y=362, x=MARGIN + 60)
    second.y = 330
    second.paragraph(
        [
            "In the vestibule below was a letter-box into which no letter",
            "would go, and an electric button from which no mortal finger",
            "could coax a ring. Also appertaining thereunto was a card",
            "bearing the name",
        ]
    )
    second.footer("4")

    third = PageBuilder().header("THE GIFT OF THE MAGI")
    third.line("“Mr. James Dillingham Young.”")
    left = [
        "Della finished her cry and",
        "attended to her cheeks with",
        "the powder rag. She stood by",
        "the window and looked out",
        "dully at a gray cat walking a",
    ]
    right = [
        "gray fence in a gray backyard.",
        "Tomorrow would be Christmas",
        "Day, and she had only $1.87",
        "with which to buy Jim a",
        "present.",
    ]
    y = third.y - LEADING
    for row, (left_line, right_line) in enumerate(zip(left, right, strict=True)):
        # Drawn left, right, left, right…: the drawing order isn't the reading order.
        third.line(left_line, y=y, x=MARGIN + (18 if row == 0 else 0))
        third.line(right_line, y=y, x=MARGIN + 180)
        y -= LEADING
    third.line("Read the whole story free (https://www.gutenberg.org/ebooks/7256).", y=y - 14,
               x=MARGIN + 18)  # fmt: skip
    third.footer("5")
    return [also_by.page, contents.page, first.page, second.page, third.page]


