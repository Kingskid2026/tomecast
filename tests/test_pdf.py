def spoken(result: CleanupResult) -> list[tuple[str, tuple[str, ...]]]:
    """The chapters that will be voiced: (title, paragraphs)."""
    return [
        (result.book.chapters[i].title, result.book.chapters[i].paragraphs) for i in result.kept
    ]


