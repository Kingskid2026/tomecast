def _story_page(heading: str | None, paragraphs: list[list[str]], *, size: float = 16) -> PdfPage:
    builder = PageBuilder()
    if heading is not None:
        builder.heading(heading, size=size)
    for lines in paragraphs:
        builder.paragraph(lines)
    return builder.page


def test_chapters_come_from_bookmarks(tmp_path: Path) -> None:
    title_page = PageBuilder(top=PAGE_HEIGHT - 160)
    title_page.heading("The Gift of the Magi", size=24).line("O. Henry")
    one = _story_page("One Dollar and Eighty-Seven Cents", [["One dollar and eighty-seven cents."]])
    two = PageBuilder()
    two.paragraph(["That was all."], indent=0)
    two.gap(40)
    heading_top = two.y + 11
    two.heading("Mr. James Dillingham Young", size=16)
    two.paragraph(["In the vestibule below was a letter-box."])
    outline = [
        Bookmark("Title Page", 0),
        Bookmark(
            "Part One",
            1,
            children=(
                Bookmark("Chapter 1: One Dollar and Eighty-Seven Cents", 1),
                Bookmark(
                    "Chapter 2. Mr. James Dillingham Young",
                    2,
                    top=heading_top,
                    children=(Bookmark("Too deep to be a chapter", 2),),
                ),
            ),
        ),
    ]
    path = build_pdf(tmp_path / "outline.pdf", [title_page.page, one, two.page], outline=outline)

    chapters = read_pdf(path).chapters

    assert [(c.title, c.paragraphs) for c in chapters] == [
        ("Title Page", ("The Gift of the Magi", "O. Henry")),
        ("Part One", ()),
        # The headings that repeat the bookmark's title are dropped: the title is read first.
        ("Chapter 1: One Dollar and Eighty-Seven Cents",
         ("One dollar and eighty-seven cents.", "That was all.")),
        ("Chapter 2. Mr. James Dillingham Young", ("In the vestibule below was a letter-box.",)),
    ]  # fmt: skip


